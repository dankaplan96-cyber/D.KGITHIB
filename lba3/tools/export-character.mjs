// Export a character's rest-pose mesh (body, arms, hands, shoes, face parts, medallion) to OBJ with vertex colours,
// for review in Blender or any viewer. The game itself builds the mesh from src/game/characters.js (the source).
//   python3 -m http.server 8123 &   node tools/export-character.mjs twinsen [port]
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const name = process.argv[2] || 'twinsen', port = process.argv[3] || '8123';
let chromium;
for (const p of ['playwright', '/opt/node-tools/node_modules/playwright/index.mjs']) { try { ({ chromium } = await import(p)); break; } catch { /* next */ } }
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
await page.goto(`http://localhost:${port}/lookdev.html?c=${name}&views=0&labels=0&props=0`, { waitUntil: 'load', timeout: 300000 });
await page.waitForFunction(() => window.lookdev, null, { timeout: 300000 });
const obj = await page.evaluate(async (name) => {
  const CH = await import('./src/game/characters.js');
  const THREE = await import('three');
  const rig = CH.createCharacter(name);
  rig.root.updateMatrixWorld(true);
  const out = [`# ${name} — rest pose, metres, Y up, +Z forward. Generated by tools/export-character.mjs`];
  let base = 1;
  const v = new THREE.Vector3(), c = new THREE.Color();
  rig.root.traverse((m) => {
    if (!m.isMesh || !m.visible) return;
    const g = m.geometry, pos = g.attributes.position, col = g.attributes.color;
    const mat = Array.isArray(m.material) ? m.material[0] : m.material;
    // skinned meshes: rest pose = bind pose, so the bind-space positions are the shape
    const M = m.isSkinnedMesh ? m.matrixWorld : m.matrixWorld;
    out.push(`o ${m.name || m.type}_${base}`);
    for (let i = 0; i < pos.count; i++) {
      v.fromBufferAttribute(pos, i).applyMatrix4(M);
      if (col) c.fromBufferAttribute(col, i); else c.copy(mat.color || new THREE.Color('#ffffff'));
      out.push(`v ${v.x.toFixed(4)} ${v.y.toFixed(4)} ${v.z.toFixed(4)} ${c.r.toFixed(3)} ${c.g.toFixed(3)} ${c.b.toFixed(3)}`);
    }
    const idx = g.index;
    const n = idx ? idx.count : pos.count;
    for (let i = 0; i < n; i += 3) {
      const a = (idx ? idx.getX(i) : i) + base, b = (idx ? idx.getX(i + 1) : i + 1) + base, d = (idx ? idx.getX(i + 2) : i + 2) + base;
      out.push(`f ${a} ${b} ${d}`);
    }
    base += pos.count;
  });
  return out.join('\n');
}, name);
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'art', 'characters', name, 'export');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, `${name}.obj`), obj);
console.log('wrote', path.join(dir, `${name}.obj`), (obj.length / 1e6).toFixed(1), 'MB');
await browser.close();
